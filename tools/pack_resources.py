"""Build the importable resource bundle; PyInstaller includes it as Python data."""
import base64
import hashlib
import io
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
files = [ROOT / "assets/app.ico"] + sorted((ROOT / "assets/static").rglob("*"))
manifest = {}
archive = io.BytesIO()
with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED) as bundle:
    for path in files:
        if not path.is_file():
            continue
        name = "app.ico" if path.name == "app.ico" and path.parent.name == "assets" else path.relative_to(ROOT / "assets/static").as_posix()
        data = path.read_bytes()
        manifest[name] = hashlib.sha256(data).hexdigest()
        info = zipfile.ZipInfo(name, date_time=(2026, 1, 1, 0, 0, 0))
        info.compress_type = zipfile.ZIP_DEFLATED
        bundle.writestr(info, data)

payload = base64.b85encode(archive.getvalue()).decode("ascii")
header = '''# Generated by tools/pack_resources.py. Includes font copyright/OFL.txt.
import base64
import hashlib
import io
import os
import zipfile
from pathlib import Path

def ensure_resources(data_dir: Path) -> Path:
    """Update only managed resources; config, searches and logs are untouched."""
    root = data_dir / "resources"
    root.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(io.BytesIO(base64.b85decode(PACKED_RESOURCES))) as bundle:
        for name, digest in RESOURCE_HASHES.items():
            destination = root / name
            current = hashlib.sha256()
            if destination.is_file():
                with destination.open("rb") as stream:
                    for chunk in iter(lambda: stream.read(65536), b""):
                        current.update(chunk)
                if current.hexdigest() == digest:
                    continue
            destination.parent.mkdir(parents=True, exist_ok=True)
            temporary = destination.with_name(destination.name + ".tmp")
            with bundle.open(name) as source, temporary.open("wb") as target:
                for chunk in iter(lambda: source.read(65536), b""):
                    target.write(chunk)
            os.replace(temporary, destination)
    return root

'''
text = header + "RESOURCE_HASHES = " + repr(manifest) + "\nPACKED_RESOURCES = (\n"
text += "\n".join("    " + repr(payload[i:i + 100]) for i in range(0, len(payload), 100)) + "\n)\n"
(ROOT / "resource_bundle.py").write_text(text, encoding="utf-8")
print(f"Embedded {len(manifest)} resources ({len(archive.getvalue()):,} bytes)")
